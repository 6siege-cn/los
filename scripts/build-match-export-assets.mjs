// Raster copies for canvas exports: some mobile engines cannot draw viewBox-only SVG images reliably.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {dirname,join} from 'node:path';
import manifest from '../operator-selection/src/asset-manifest.js';
const require=createRequire(import.meta.url);
let sharp;
try{sharp=require('sharp');}catch{sharp=createRequire(join(dirname(process.execPath),'../package.json'))('sharp');}
const root=new URL('../operator-selection/',import.meta.url);
await mkdir(new URL('assets/export/',root),{recursive:true});
const result={avatars:{},marks:{}};
for(const [group,entries,size] of [
  ['avatars',Object.entries(manifest.avatars),192],
  ['marks',['thumbs-up','thumbs-down','skull','crosshair'].map(key=>[key,`assets/icons/record-${key}.svg`]),64]
]){
  for(const [key,path] of entries){
    const bytes=await sharp(await readFile(new URL(path,root)),{density:144}).resize(size,size,{fit:'contain',background:'#00000000'}).png({compressionLevel:9}).toBuffer();
    const hash=createHash('sha256').update(bytes).digest('hex').slice(0,20);
    const output=`assets/export/${group}-${hash}.png`;
    await writeFile(new URL(output,root),bytes);result[group][key]=output;
  }
}
await writeFile(new URL('src/export-assets.js',root),'// Generated by scripts/build-match-export-assets.mjs\nexport default '+JSON.stringify(result,null,2)+';\n');
await writeFile(new URL('export-cache-manifest.js',root),'// Generated by scripts/build-match-export-assets.mjs\nself.EXPORT_IMAGES = '+JSON.stringify([...new Set([...Object.values(result.avatars),...Object.values(result.marks)])],null,2)+';\n');
const revision=createHash('sha256').update(JSON.stringify(result)).digest('hex').slice(0,16);
for(const [file,pattern,replacement] of [
  ['src/config.js',/\.\/export-assets\.js(?:\?[^']*)?/,`./export-assets.js?v=${revision}`],
  ['sw.js',/\.\/export-cache-manifest\.js(?:\?[^']*)?/,`./export-cache-manifest.js?v=${revision}`]
]){
  const url=new URL(file,root),text=await readFile(url,'utf8');
  if(!pattern.test(text))throw Error('Missing export reference in '+file);
  await writeFile(url,text.replace(pattern,replacement));
}
console.log(`Export PNG assets: ${Object.keys(result.avatars).length} avatars, ${Object.keys(result.marks).length} marks`);
