import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {dirname,join} from 'node:path';
import {readOperators} from './build-operators.mjs';

const require=createRequire(import.meta.url);
let sharp;
try {sharp=require('sharp');}
catch {sharp=createRequire(join(dirname(process.execPath),'../package.json'))('sharp');}
const root=new URL('../operator-selection/',import.meta.url);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const operators=readOperators();
const tokenKeys=[...new Set(operators.flatMap(op=>[op.hp,op.destruction,...op.close,...op.medium,...op.long]))];
const iconNames=['crossed-pickaxes.png','ribbon-badge.png','medal-round-solid-alt.png','prohibited-large.png','refresh-clockwise.png','undo-return.svg','rules-menu.svg','settings-gear.svg'];
const manifest={revision:'',avatars:{},tokens:{},icons:{},panels:{},sources:[]};
await mkdir(new URL('assets/optimized/',root),{recursive:true});
async function add(group,key,source,maxSize){
  const input=await readFile(new URL(source,root));
  const ext=source.endsWith('.svg')?'svg':maxSize?'webp':'png';
  const output=maxSize?await sharp(input).rotate().resize({width:maxSize,height:maxSize,fit:'inside',withoutEnlargement:true})
    .webp(group==='panels'?{quality:86,effort:5}:{lossless:true,effort:6}).toBuffer():input;
  const outputHash=hash(output);
  const path=`assets/optimized/${group}-${outputHash.slice(0,20)}.${ext}`;
  await writeFile(new URL(path,root),output);
  manifest[group][key]=path;
  manifest.sources.push({group,key,source,sourceHash:hash(input),path,outputHash,originalBytes:input.length,bytes:output.length});
}
for(const file of [...new Set(operators.map(op=>op.avatar))])await add('avatars',file,'assets/operators/badges/'+file);
for(const key of tokenKeys)await add('tokens',key,'assets/tokens/'+key+'.png',128);
for(const file of iconNames)await add('icons',file,'assets/icons/'+file);
for(const file of [...new Set(operators.map(op=>op.panel))])await add('panels',file,'assets/operators/中文干员面板26.9.4/'+file,2560);
manifest.revision=hash(JSON.stringify(manifest)).slice(0,16);
await writeFile(new URL('src/asset-manifest.js',root),'// Generated by npm run optimize-assets. Do not edit.\nexport default '+JSON.stringify(manifest,null,2)+';\n');
const cacheManifest={revision:manifest.revision,core:[...new Set([...Object.values(manifest.avatars),...Object.values(manifest.tokens),...Object.values(manifest.icons)])],panels:[...new Set(Object.values(manifest.panels))]};
await writeFile(new URL('cache-manifest.js',root),'// Generated by npm run optimize-assets.\nself.IMAGE_MANIFEST = '+JSON.stringify(cacheManifest,null,2)+';\n');
// Version the entire import chain so static hosting cannot retain an old manifest.
for(const [file,pattern,replacement] of [
  ['src/config.js',/\.\/asset-manifest\.js(?:\?[^']*)?/,`./asset-manifest.js?v=${manifest.revision}`],
  ['src/app.js',/\.\/config\.js(?:\?[^']*)?/,`./config.js?v=${manifest.revision}`],
  ['index.html',/\.\/src\/app\.js(?:\?[^\"]*)?/,`./src/app.js?v=${manifest.revision}`],
  ['sw.js',/\.\/cache-manifest\.js(?:\?[^']*)?/,`./cache-manifest.js?v=${manifest.revision}`],
]){
  const path=new URL(file,root),text=await readFile(path,'utf8');
  if(!pattern.test(text))throw Error('Missing manifest reference in '+file);
  await writeFile(path,text.replace(pattern,replacement));
}
for(const group of ['avatars','tokens','icons','panels']){
  const entries=manifest.sources.filter(s=>s.group===group);
  console.log(group,JSON.stringify({count:entries.length,before:entries.reduce((n,s)=>n+s.originalBytes,0),after:entries.reduce((n,s)=>n+s.bytes,0)}));
}
